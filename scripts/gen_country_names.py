#!/usr/bin/env python3
"""Regenerate packages/mboa_ui/lib/src/ui/inputs/country_names.g.dart.

Country names in French and English, from Unicode CLDR (cldr-json,
Unicode License V3) — the reference the phone's own settings use. The
dial codes and number lengths come from the phone_numbers_parser package
(Google's libphonenumber metadata); only the names live here.

    python3 scripts/gen_country_names.py
"""
import json
import pathlib
import urllib.request

BASE = "https://raw.githubusercontent.com/unicode-org/cldr-json/main/cldr-json/cldr-localenames-full/main/{}/territories.json"
OUT = pathlib.Path(__file__).resolve().parent.parent / "packages/mboa_ui/lib/src/ui/inputs/country_names.g.dart"


def territories(locale):
    with urllib.request.urlopen(BASE.format(locale)) as response:
        data = json.load(response)
    names = data["main"][locale]["localeDisplayNames"]["territories"]
    # Two-letter regions only; CLDR's « -alt-short » and numeric areas out.
    return {code: name for code, name in names.items() if len(code) == 2 and code.isalpha()}


def dart(text):
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'") + "'"


fr, en = territories("fr"), territories("en")
lines = [
    "// GENERATED by scripts/gen_country_names.py — do not edit by hand.",
    "// Source: Unicode CLDR (cldr-json), Unicode License V3.",
    "",
    "/// Country names by ISO 3166 code, in French and English.",
    "const Map<String, ({String fr, String en})> countryNames = {",
]
for code in sorted(set(fr) & set(en)):
    lines.append(f"  {dart(code)}: (fr: {dart(fr[code])}, en: {dart(en[code])}),")
lines.append("};")
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"{OUT}: {len(set(fr) & set(en))} countries")
