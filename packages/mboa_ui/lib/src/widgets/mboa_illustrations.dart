import 'package:flutter/widgets.dart';

/// The Mboa illustrations (Brandbook v2 §05).
///
/// Two drawings, named for what they are rather than numbered, because the
/// numbers said nothing and the old three were abstract washes that belonged
/// to no rule:
///
///  * [pattern] — the brand's wallpaper, a field of small monograms on Vert
///    Forêt. Behind the logo on brand surfaces: splash, auth hero, the profile
///    header.
///  * [skyline] — a row of gabled houses, flat and geometric, pitched at the
///    45° of the logo's own construction grid. **Onboarding, empty states and
///    errors only**, which is where §05 allows illustration at all.
///
/// Both are generated by `scripts/brand/make_assets.py`; restyle there.
///
/// The brandbook also asks for African characters in illustration. There are
/// none here: a figure drawn badly says more, and worse, than no figure. That
/// one waits for a designer.
class MboaIllustrations {
  const MboaIllustrations._();

  static const String _path = 'assets/images/illustrations';
  static const String _package = 'mboa_ui';

  /// The brand wallpaper. Already carries Vert Forêt, so it needs no ground
  /// under it — though one behind avoids a flash while the asset decodes.
  static Widget pattern({
    double? width,
    double? height,
    BoxFit fit = BoxFit.cover,
    Alignment alignment = Alignment.center,
  }) =>
      Image.asset(
        '$_path/brand_pattern.png',
        package: _package,
        width: width,
        height: height,
        fit: fit,
        alignment: alignment,
      );

  /// A neighbourhood of gables, on transparent ground so it sits on any
  /// surface. Anchor it to the bottom of its box: these are houses, and houses
  /// stand on something.
  static Widget skyline({
    double? width,
    double? height,
    BoxFit fit = BoxFit.fitWidth,
    Alignment alignment = Alignment.bottomCenter,
  }) =>
      Image.asset(
        '$_path/brand_skyline.png',
        package: _package,
        width: width,
        height: height,
        fit: fit,
        alignment: alignment,
      );
}
